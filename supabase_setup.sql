-- BLACKLIGHT V2 database setup
-- Run in Supabase SQL Editor. Do not put service_role keys in website files.
create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  created_at timestamptz not null default now()
);
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  role text not null check (role in ('admin','admin_plus')),
  created_at timestamptz not null default now()
);
create table if not exists public.applications (
  id bigint generated by default as identity primary key,
  game_username text not null,
  real_age int not null check (real_age >= 10 and real_age <= 99),
  join_goal text not null,
  rubika_id text not null,
  game_test text not null,
  skill_rating int not null check (skill_rating between 0 and 10),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
alter table public.admin_users enable row level security;
alter table public.applications enable row level security;

create or replace function public.is_blacklight_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.admin_users where user_id=auth.uid() and role in ('admin','admin_plus')); $$;
create or replace function public.is_blacklight_admin_plus()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.admin_users where user_id=auth.uid() and role='admin_plus'); $$;

drop policy if exists "public submit applications" on public.applications;
create policy "public submit applications" on public.applications for insert to anon, authenticated with check (true);
drop policy if exists "admins read applications" on public.applications;
create policy "admins read applications" on public.applications for select to authenticated using (public.is_blacklight_admin());
drop policy if exists "admins update applications" on public.applications;
create policy "admins update applications" on public.applications for update to authenticated using (public.is_blacklight_admin()) with check (public.is_blacklight_admin());
drop policy if exists "admins delete applications" on public.applications;
create policy "admins delete applications" on public.applications for delete to authenticated using (public.is_blacklight_admin());

drop policy if exists "users read own profile" on public.profiles;
create policy "users read own profile" on public.profiles for select to authenticated using (user_id=auth.uid());
drop policy if exists "admins read profiles" on public.profiles;
create policy "admins read profiles" on public.profiles for select to authenticated using (public.is_blacklight_admin());

drop policy if exists "admins read admin list" on public.admin_users;
create policy "admins read admin list" on public.admin_users for select to authenticated using (public.is_blacklight_admin());
drop policy if exists "admin plus grants or revokes admins" on public.admin_users;
create policy "admin plus grants or revokes admins" on public.admin_users for all to authenticated
using (public.is_blacklight_admin_plus() and role='admin')
with check (public.is_blacklight_admin_plus() and role='admin');

